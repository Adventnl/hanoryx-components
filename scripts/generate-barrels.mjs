#!/usr/bin/env node
/* Regenerates the index.js barrel of every library area from the exports of the
   files beside it, so a new component is public the moment its file exists.

     node scripts/generate-barrels.mjs          write the barrels
     node scripts/generate-barrels.mjs --check  fail if any barrel is stale

   A file contributes its named exports; a file with only a default export is
   exported under the default's own name (or the file's name). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readExports, walk } from './lib/exports.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const check = process.argv.includes('--check');
const HEADER = '/* Generated by scripts/generate-barrels.mjs — edit the files beside it, not this list. */\n';

/** dir (relative to src) -> options */
const AREAS = [
  { dir: 'core/hooks' },
  { dir: 'core/utils' },
  { dir: 'core/motion' },
  { dir: 'core/providers' },
  { dir: 'core/performance' },
  { dir: 'core/site' },
  { dir: 'kit', recursive: true, exclude: [/\/demos\//, /\/internal\/(?!toastContext)/] },
  { dir: 'fx' },
  { dir: 'ui' },
  { dir: 'reveal' },
  { dir: 'scenes', files: ['SceneCanvas.jsx', 'SectionScene.jsx', 'library/index.js'] },
  { dir: 'page', recursive: true },
  { dir: 'shell', recursive: true },
  { dir: 'signatures' },
  { dir: 'closers' },
  { dir: 'stage', recursive: true },
];

/** Names that two files in one area both export: keep the second under another name. */
const ALIASES = {
  'core/motion': { './sceneBudget': { registerScene: 'registerSceneController' } },
};

const isModule = (p) => /\.(jsx?|mjs)$/.test(p) && !/\.(doc|test|demo)\.(jsx?|mjs)$/.test(p) && path.basename(p) !== 'index.js';
const conflicts = [];
let stale = 0;

function write(file, text) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === text) return;
  stale += 1;
  if (!check) fs.writeFileSync(file, text);
}

function barrelFor(area) {
  const base = path.join(SRC, area.dir);
  const files = area.files
    ? area.files.map((f) => path.join(base, f))
    : area.recursive ? walk(base, (p) => isModule(p) && !(area.exclude ?? []).some((re) => re.test(p.replace(/\\/g, '/')))) : fs.readdirSync(base).map((f) => path.join(base, f)).filter((p) => fs.statSync(p).isFile() && isModule(p));
  files.sort((a, b) => a.localeCompare(b));
  const seen = new Map();
  const lines = [];
  for (const f of files) {
    const rel = './' + path.relative(base, f).replace(/\\/g, '/').replace(/\.(jsx?|mjs)$/, '').replace(/\/index$/, '');
    const { named, defaultName, hasDefault } = readExports(f);
    const alias = ALIASES[area.dir]?.[rel] ?? {};
    const names = named.map((n) => (alias[n] ? `${n} as ${alias[n]}` : n));
    let defaultAs = null;
    if (hasDefault) {
      const nm = defaultName ?? path.basename(f).replace(/\.(jsx?|mjs)$/, '');
      if (!named.includes(nm)) defaultAs = nm;
    }
    const take = (nm) => {
      nm = nm.split(' as ').pop();
      if (seen.has(nm)) { conflicts.push(`${area.dir}: ${nm} is exported by ${seen.get(nm)} and ${rel}`); return false; }
      seen.set(nm, rel);
      return true;
    };
    const ok = names.filter(take);
    const parts = ok.slice();
    if (defaultAs && take(defaultAs)) parts.push(`default as ${defaultAs}`);
    if (parts.length) lines.push(`export { ${parts.join(', ')} } from '${rel}';`);
  }
  write(path.join(base, 'index.js'), HEADER + lines.join('\n') + '\n');
}

AREAS.forEach(barrelFor);

/* core/index.js — every core area in one import */
write(path.join(SRC, 'core/index.js'), HEADER + ['hooks', 'utils', 'motion', 'providers', 'performance', 'site'].map((d) => `export * from './${d}';`).join('\n') + '\n');

/* specimens/index.js — one namespace per family */
const families = fs.readdirSync(path.join(SRC, 'specimens')).filter((d) => fs.existsSync(path.join(SRC, 'specimens', d, 'index.js'))).sort();
const ns = (slug) => slug[0].toUpperCase() + slug.slice(1);
write(path.join(SRC, 'specimens/index.js'),
  HEADER + `export { chapters, engines, showcasePages, pageBySlug, pagesIn, showcasePath, showcaseNumber, MIN_SPECIMENS } from './families.js';\n`
  + families.map((s) => `export * as ${ns(s)} from './${s}';`).join('\n') + '\n');

if (conflicts.length) { console.error('Barrel conflicts (first export wins):\n  ' + conflicts.join('\n  ')); }
if (check && stale) { console.error(`${stale} barrel(s) are stale — run node scripts/generate-barrels.mjs`); process.exit(1); }
console.log(check ? 'barrels are current' : `barrels written (${stale} changed)`);
