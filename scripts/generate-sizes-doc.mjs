#!/usr/bin/env node
/* Writes docs/sizes.md from the measured sizes (docs/generated/sizing.json).

     npm run docs:sizing && node scripts/generate-sizes-doc.mjs

   Every entry was rendered alone in a parent 360, 768 and 1200 px wide, in a
   real browser at a 16 px root size, with reduced motion on. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/generated/manifest.json'), 'utf8'));
const sizing = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/generated/sizing.json'), 'utf8'));

const m = (e) => e.sizing?.measured ?? sizing[e.id]?.measured;
const cell = (e, w) => { const v = m(e)?.at?.[w]; return v ? `${Math.round(v.w)}×${Math.round(v.h)}` : '—'; };
const ratio = (e) => { const at = m(e)?.at; if (!at) return '—'; const v = at[1200] ?? Object.values(at).pop(); return v?.h ? (v.w / v.h).toFixed(2) : '—'; };
const esc = (s) => { const t = String(s ?? ''); return !t || /^0(px)?( 0(px)?)*$/.test(t) ? '—' : t.replace(/\|/g, '\\|'); };

const out = ['# Measured sizes', '',
  'Generated by `scripts/generate-sizes-doc.mjs` from `docs/generated/sizing.json`. Previews are rendered in parents 360, 768 and 1200 px wide (real Chromium, 16 px root, reduced motion on). Parts needing a parent composition use a contextual example; each entry records its measurement scope. Sizes are `width×height` in px.', '',
  '| Behaviour | Meaning |', '| --- | --- |',
  '| **fill** | width = the parent\'s width at every size |', '| **capped** | follows the parent up to a maximum, then stops |', '| **intrinsic** | the same width whatever the parent is (including a component capped below 360 px) |', '| **fluid** | changes with the parent, but not one-to-one |', '',
  'A component that is `intrinsic` and wider than a phone (**overflow** column) will scroll sideways in a 360 px parent. Fix it with a parent that scrolls or a layout that stacks — never by setting a width on the component.', ''];

function table(title, entries, { minTouch = true } = {}) {
  const rows = entries.filter((e) => m(e));
  if (!rows.length) return;
  out.push(`## ${title}`, '', `| Name | Behaviour | @360 | @768 | @1200 | Ratio | Padding | Radius | Smallest control | Overflow | Scope |`, '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const e of rows) {
    const s = m(e);
    out.push(`| \`${e.name}\` | ${s.behavior ?? '—'} | ${cell(e, 360)} | ${cell(e, 768)} | ${cell(e, 1200)} | ${ratio(e)} | ${esc(s.padding)} | ${esc(s.radius)} | ${esc(s.minTouch) || '—'} | ${s.overflowsAt360 ? '**yes**' : ''} | ${esc(s.scope)} |`);
  }
  out.push('');
}

const by = (area, family) => manifest.entries.filter((e) => e.area === area && (!family || e.family === family) && !e.parent && e.kind !== 'hook');
for (const [fam, label] of Object.entries(manifest.kitFamilies)) table(`Kit — ${label}`, by('kit', fam));
table('Foreground toolkit', by('fx'));
table('Site UI', by('ui'));
table('Page blocks', by('page', 'blocks'));

/* compositions: one row each, measured at 1200 only */
for (const [area, label] of [['signatures', 'Signatures'], ['closers', 'Closers']]) {
  const rows = by(area).filter((e) => m(e));
  if (!rows.length) continue;
  out.push(`## ${label}`, '', 'Page sections: they fill any parent. Height is at a 1200 px parent.', '', '| Name | Height |', '| --- | --- |');
  for (const e of rows) out.push(`| \`${e.name}\` | ${Math.round(m(e).at[1200].h)} px |`);
  out.push('');
}

/* specimens: summarised by family */
out.push('## Specimens', '', 'Each specimen is drawn at its natural size. Per family: how many fill, cap or hug their parent, and the typical and largest footprint (at a 1200 px parent). Per-specimen numbers are in the manifest (`hanoryx family <slug>`, or the docs-site page of the specimen).', '',
  '| Family | Specimens | fill | capped | intrinsic | fluid | Median w×h | Widest | Tallest | Overflow @360 |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.floor(s.length / 2)] : 0; };
for (const f of manifest.families) {
  const es = manifest.entries.filter((e) => e.area === 'specimens' && e.family === f.slug && m(e));
  if (!es.length) continue;
  const cnt = (b) => es.filter((e) => m(e).behavior === b).length;
  const w = es.map((e) => m(e).at[1200].w); const h = es.map((e) => m(e).at[1200].h);
  const widest = es.reduce((a, e) => (m(e).at[1200].w > m(a).at[1200].w ? e : a));
  const tallest = es.reduce((a, e) => (m(e).at[1200].h > m(a).at[1200].h ? e : a));
  const over = es.filter((e) => m(e).overflowsAt360).length;
  out.push(`| ${f.title} | ${es.length} | ${cnt('fill')} | ${cnt('capped')} | ${cnt('intrinsic')} | ${cnt('fluid')} | ${Math.round(median(w))}×${Math.round(median(h))} | ${Math.round(Math.max(...w))} (${widest.name}) | ${Math.round(Math.max(...h))} (${tallest.name}) | ${over || ''} |`);
}
out.push('');

const total = Object.keys(sizing).length;
out.push(`_${total} entries measured._`, '');
fs.writeFileSync(path.join(ROOT, 'docs/sizes.md'), out.join('\n'));
console.log(`docs/sizes.md written (${total} entries measured)`);
