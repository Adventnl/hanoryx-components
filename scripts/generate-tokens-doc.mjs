#!/usr/bin/env node
/* Writes docs/tokens.md from src/styles/tokens.css — the values, and what the
   fluid ones (clamp) come to in pixels at the widths that matter.

     node scripts/generate-tokens-doc.mjs
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const css = fs.readFileSync(path.join(ROOT, 'src/styles/tokens.css'), 'utf8');
const WIDTHS = [360, 768, 1280, 1920];
const REM = 16;

/* ---- parse :root custom properties, keeping the section heading and the trailing comment ---- */
const rows = [];
let section = '';
for (const raw of css.split('\n')) {
  const sec = /\/\*\s*---\s*(.+?)\s*---\s*\*\//.exec(raw);
  if (sec) { section = sec[1]; continue; }
  const m = /^\s*(--[\w-]+):\s*([^;]+);\s*(?:\/\*\s*(.*?)\s*\*\/)?/.exec(raw);
  if (m) rows.push({ section, name: m[1], value: m[2].trim(), note: m[3] || '' });
}

/* ---- evaluate a length expression (rem, px, vw, clamp, min, max, calc is not used here) ---- */
function evalLen(expr, vw, vars) {
  const resolve = (s) => s.replace(/var\((--[\w-]+)\)/g, (_, n) => (vars.get(n) ?? 'NaN'));
  const e = resolve(expr.trim());
  const num = (s) => {
    s = s.trim();
    let m;
    if ((m = /^(-?[\d.]+)rem$/.exec(s))) return parseFloat(m[1]) * REM;
    if ((m = /^(-?[\d.]+)px$/.exec(s))) return parseFloat(m[1]);
    if ((m = /^(-?[\d.]+)vw$/.exec(s))) return (parseFloat(m[1]) * vw) / 100;
    if ((m = /^(-?[\d.]+)$/.exec(s))) return parseFloat(m[1]);
    return NaN;
  };
  const args = (inner) => {
    const out = []; let depth = 0; let cur = '';
    for (const ch of inner) {
      if (ch === '(') depth++;
      if (ch === ')') depth--;
      if (ch === ',' && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
    }
    out.push(cur);
    return out;
  };
  const ev = (s) => {
    s = s.trim();
    let m;
    if ((m = /^clamp\((.*)\)$/.exec(s))) { const [a, b, c] = args(m[1]).map(ev); return Math.min(Math.max(b, a), c); }
    if ((m = /^min\((.*)\)$/.exec(s))) return Math.min(...args(m[1]).map(ev));
    if ((m = /^max\((.*)\)$/.exec(s))) return Math.max(...args(m[1]).map(ev));
    return num(s);
  };
  return ev(e);
}

const vars = new Map(rows.map((r) => [r.name, r.value]));
const fmt = (n) => (Number.isFinite(n) ? `${Math.round(n * 10) / 10}px` : '—');
const isLen = (v) => /(rem|px|vw|clamp\(|min\(|max\()/.test(v) && !/(gradient|rgba?\(|#|cubic|\s{2})/.test(v) && !/^var\(/.test(v);

const bySection = new Map();
for (const r of rows) {
  if (!bySection.has(r.section)) bySection.set(r.section, []);
  bySection.get(r.section).push(r);
}

const out = [];
out.push('# Tokens', '', 'Generated by `scripts/generate-tokens-doc.mjs` from `src/styles/tokens.css`. **Every component reads these variables; an app should too — never a raw colour, size or duration.**', '');
out.push('Fluid values (`clamp(…)`) are shown as what they come to at four viewport widths, at a 16 px root size.', '');
for (const [name, list] of bySection) {
  out.push(`## ${name.charAt(0) + name.slice(1).toLowerCase()}`, '');
  const fluid = list.some((r) => /clamp\(/.test(r.value));
  if (fluid) {
    out.push(`| Token | Value | ${WIDTHS.map((w) => `${w}px`).join(' | ')} | Note |`, `| --- | --- | ${WIDTHS.map(() => '---').join(' | ')} | --- |`);
    for (const r of list) {
      const cells = WIDTHS.map((w) => (isLen(r.value) ? fmt(evalLen(r.value, w, vars)) : ''));
      out.push(`| \`${r.name}\` | \`${r.value}\` | ${cells.join(' | ')} | ${r.note} |`);
    }
  } else {
    out.push('| Token | Value | Px | Note |', '| --- | --- | --- | --- |');
    for (const r of list) {
      const px = /^-?[\d.]+(rem|px)$/.test(r.value) ? fmt(evalLen(r.value, 1280, vars)) : '';
      out.push(`| \`${r.name}\` | \`${r.value}\` | ${px} | ${r.note} |`);
    }
  }
  out.push('');
}

/* ---- the global utility classes ---- */
out.push('## Global classes', '', 'Defined in `src/styles/layout.css` and `typography.css`, loaded by `hanoryx-components/styles`.', '');
const glob = [
  ['.container', 'Page width: `max-width: var(--maxw)`, centred, side padding `var(--gutter)`. Every page block is wrapped in one.'],
  ['.section', 'A page block: `padding-block: var(--section-pad)` (80–176 px).'],
  ['.stage', 'Full-viewport stage (`100svh`), content centred vertically.'],
  ['.stack, .stack-4/5/6', 'Vertical flex with `--space-4/5/6` gaps.'],
  ['.cluster', 'Wrapping horizontal row, centred on the cross axis, `--space-4` gap.'],
  ['.grid, .grid--3, .grid--split', 'Grid with `--space-5` gap; `--3` is three columns (two under 1024 px, one under 720 px); `--split` is two equal columns (one under 720 px).'],
  ['.divider', '1 px hairline that fades at both ends.'],
  ['.measure', 'Caps a text column at `62ch`.'],
  ['.display, .heading-hero, .heading-1/2/3', 'Serif headings at `--fs-display`, `--fs-hero`, `--fs-h1/h2/h3`.'],
  ['.lead, .body, .body-sm', 'Sans text at `--fs-lead`, `--fs-body`, `--fs-sm`.'],
  ['.eyebrow, .data-label, .mono', 'The mono “system voice”: uppercase, `--ls-label` tracking, `--fs-label`. `.eyebrow` adds a red dot.'],
];
out.push('| Class | What it does |', '| --- | --- |', ...glob.map(([c, d]) => `| \`${c}\` | ${d} |`), '');

fs.writeFileSync(path.join(ROOT, 'docs/tokens.md'), out.join('\n'));
console.log(`docs/tokens.md written (${rows.length} tokens)`);
