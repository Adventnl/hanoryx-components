#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launch, BASE } from './browser.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 1000 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const passed = [];
try {
  await page.goto(`${BASE}/#/raw/none`);
  await page.evaluate(async (url) => { const module = await import(url); window.unmountFixture = module.mount(); }, `/@fs/${ROOT.replaceAll('\\', '/')}/scripts/qa/fixtures/HookHarness.jsx`);
  const host = page.locator('[data-harness]');
  await host.waitFor();
  const hooks = async () => JSON.parse(await host.locator('[data-hooks]').textContent());
  const day = host.locator('[data-date="2024-02-28"]');
  await day.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await host.locator('[data-date]').last().textContent(), '2024-02-28');
  assert.equal(await page.evaluate(() => document.activeElement.dataset.date), '2024-02-29');
  await page.keyboard.press('Enter');
  assert.equal(await host.locator('output[data-date]').textContent(), '2024-02-29');
  await page.keyboard.press('PageDown');
  await page.waitForFunction(() => document.activeElement.dataset.date === '2024-03-29');
  assert.equal(await page.evaluate(() => document.activeElement.dataset.date), '2024-03-29');
  passed.push('calendar keyboard navigation, leap-day selection and selection/focus separation');
  await host.getByLabel('End date', { exact: true }).fill('2024-02-20');
  assert.match(await host.getByRole('alert').textContent(), /End date/);
  passed.push('date-range validation');
  await host.getByLabel('Message', { exact: true }).fill('Hello');
  await host.getByRole('button', { name: 'Send', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-sent]').textContent === '["Hello"]');
  assert.equal(await host.getByLabel('Message', { exact: true }).inputValue(), '');
  await host.getByLabel('Message', { exact: true }).fill('fail');
  await host.getByRole('button', { name: 'Send', exact: true }).click();
  await host.getByText('Please retry', { exact: true }).waitFor();
  assert.equal(await host.getByLabel('Message', { exact: true }).inputValue(), 'fail');
  passed.push('chat send, clear, rejection and draft preservation');
  const separator = host.getByRole('separator', { name: 'Resize panels', exact: true });
  await separator.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await separator.getAttribute('aria-valuenow'), '41');
  await page.keyboard.press('Home'); assert.equal(await separator.getAttribute('aria-valuenow'), '20');
  await page.keyboard.press('End'); assert.equal(await separator.getAttribute('aria-valuenow'), '80');
  passed.push('resizable keyboard updates and bounds');
  const editor = host.getByRole('textbox', { name: 'Rich text', exact: true });
  await page.waitForFunction(() => document.querySelector('[contenteditable]').textContent.includes('Safe'));
  assert.equal(await editor.locator('img,script,[onerror],a[href^="javascript:"]').count(), 0);
  assert.equal(await page.evaluate(() => window.unsafe), undefined);
  await editor.fill('A clear sentence');
  await editor.evaluate(element => { const range = document.createRange(); range.selectNodeContents(element); const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range); element.dispatchEvent(new MouseEvent('mouseup', { bubbles: true })); });
  await host.getByRole('button', { name: 'Bold', exact: true }).click();
  assert.equal(await editor.locator('strong').textContent(), 'A clear sentence');
  assert.match(await host.locator('[data-html]').textContent(), /<strong>A clear sentence<\/strong>/);
  await editor.evaluate(element => {
    element.innerHTML = '<p>First paragraph</p><p>Second paragraph</p>';
    element.dispatchEvent(new InputEvent('input', { bubbles: true }));
    const range = document.createRange(); range.selectNodeContents(element);
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
    element.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }));
  });
  await host.getByRole('button', { name: 'Italic', exact: true }).click();
  assert.equal(await editor.locator('p > em').count(), 2);
  assert.equal(await editor.locator('em > p').count(), 0);
  passed.push('rich-text HTML sanitization, selection formatting and emitted value');
  assert.deepEqual((await hooks()).ids, ['a', 'b']);
  await host.getByRole('button', { name: 'Sort count' }).click();
  assert.deepEqual((await hooks()).ids, ['b', 'a']);
  await host.getByRole('button', { name: 'Sort count' }).click();
  assert.deepEqual((await hooks()).ids, ['a', 'c']);
  await host.getByRole('button', { name: 'Select page' }).click();
  assert.deepEqual((await hooks()).selected, ['a', 'c']);
  await host.getByRole('button', { name: 'Next page' }).click();
  assert.deepEqual((await hooks()).ids, ['b']);
  await host.getByRole('button', { name: 'Select page' }).click();
  assert.deepEqual((await hooks()).selected, ['a', 'c', 'b']);
  await host.getByLabel('Filter rows').fill('Alpha');
  assert.deepEqual((await hooks()).ids, ['a']);
  assert.equal((await hooks()).page, 0);
  await host.getByRole('button', { name: 'Toggle count column' }).click();
  assert.deepEqual((await hooks()).columns, ['name']);
  await host.getByRole('button', { name: 'Toggle count column' }).click();
  await host.getByRole('button', { name: 'Reorder columns' }).click();
  assert.deepEqual((await hooks()).columns, ['count', 'name']);
  await host.getByRole('button', { name: 'Expand Alpha' }).click();
  assert.deepEqual((await hooks()).expanded, ['a']);
  await host.getByRole('button', { name: 'Toggle root' }).click();
  assert.deepEqual((await hooks()).tree, ['root']);
  const resize = host.getByRole('separator', { name: 'Resize Name column' });
  await resize.focus(); await page.keyboard.press('ArrowRight');
  const state = await hooks();
  assert.equal(state.width, 170); assert.equal(state.sticky, 170);
  assert.deepEqual(state.groups, [2, 1]); assert.equal(state.index, 1); assert.equal(state.missing, -1); assert.equal(state.status, 'healthy');
  passed.push('table sort/filter/page/selection/columns/tree/resize/sticky/group/index/status composition');
  const motion = host.getByRole('region', { name: 'Motion checks', exact: true });
  const offscreen = host.getByRole('region', { name: 'Offscreen motion check', exact: true });
  assert.match(await motion.getByRole('button', { name: /^Battery/ }).getAttribute('aria-label'), /42 percent/);
  assert.match(await motion.getByRole('button', { name: /^Tank/ }).getAttribute('aria-label'), /55 percent/);
  const node = motion.getByRole('button', { name: 'Node 1, drag it or use the arrow keys', exact: true });
  await node.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await node.evaluate(element => element.parentElement.getAttribute('transform')), 'translate(55.00 50.00)');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForTimeout(500);
  assert.doesNotMatch(await motion.getByRole('button', { name: /^Battery/ }).getAttribute('aria-label'), /42 percent/);
  assert.match(await offscreen.getByRole('button', { name: /^Battery/ }).getAttribute('aria-label'), /42 percent/);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForTimeout(100);
  const stopped = await motion.getByRole('button', { name: /^Battery/ }).getAttribute('aria-label');
  await page.waitForTimeout(350);
  assert.equal(await motion.getByRole('button', { name: /^Battery/ }).getAttribute('aria-label'), stopped);
  passed.push('reduced-motion pause, visibility gating, active-loop control and direct graph keyboard editing');
  assert.deepEqual(errors, []);
  await page.evaluate(() => window.unmountFixture());
  fs.writeFileSync(path.join(ROOT, 'docs/generated/interaction-report.json'), JSON.stringify({ generatedAt: new Date().toISOString(), passed, errors }, null, 2));
  console.log(`${passed.length} browser interaction groups passed.`);
} finally { await browser.close(); }
