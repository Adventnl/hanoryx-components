export const raster = (text) => {
  const rows = Array.from({ length: 7 }, () => '');
  [...text].forEach((ch, i) => {
    for (let y = 0; y < 7; y += 1) rows[y] += FONT[ch][y] + (i < text.length - 1 ? '0' : '');
  });
  return rows;
};

